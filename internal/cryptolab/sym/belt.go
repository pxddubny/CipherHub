type Belt struct {
	subkeys [8]uint32
}

func NewBelt(key []byte) (*Belt, error) {
	if len(key) != beltKeySize {
		return nil, fmt.Errorf("belt: key must be %d bytes, got %d", beltKeySize, len(key))
	}

	b := &Belt{}
	for i := 0; i < 8; i++ {
		b.subkeys[i] = binary.LittleEndian.Uint32(key[i*4 : (i+1)*4])
	}
	return b, nil
}

func (m *Belt) BlockSize() int { return beltBlockSize }

func (m *Belt) EncryptBlock(dst, src []byte) {
	if len(src) < beltBlockSize || len(dst) < beltBlockSize {
		panic("belt: block too short")
	}

	k := m.roundKeys()

	a := binary.LittleEndian.Uint32(src[0:4])
	b := binary.LittleEndian.Uint32(src[4:8])
	c := binary.LittleEndian.Uint32(src[8:12])
	d := binary.LittleEndian.Uint32(src[12:16])

	for i := 1; i <= 8; i++ {
		base := 7 * (i - 1)

		b ^= g5(a + k[base])
		c ^= g21(d + k[base+1])
		a -= g13(b + k[base+2])

		e := g21(b+c+k[base+3]) ^ uint32(i)
		b += e
		c -= e

		d += g13(c + k[base+4])
		b ^= g21(a + k[base+5])
		c ^= g5(d + k[base+6])

		a, b = b, a
		c, d = d, c
		b, c = c, b
	}

	binary.LittleEndian.PutUint32(dst[0:4], b)
	binary.LittleEndian.PutUint32(dst[4:8], d)
	binary.LittleEndian.PutUint32(dst[8:12], a)
	binary.LittleEndian.PutUint32(dst[12:16], c)
}

func (m *Belt) DecryptBlock(dst, src []byte) {
	if len(src) < beltBlockSize || len(dst) < beltBlockSize {
		panic("belt: block too short")
	}

	k := m.roundKeys()

	a := binary.LittleEndian.Uint32(src[8:12])
	b := binary.LittleEndian.Uint32(src[0:4])
	c := binary.LittleEndian.Uint32(src[12:16])
	d := binary.LittleEndian.Uint32(src[4:8])

	for i := 8; i >= 1; i-- {
		base := 7 * (i - 1)

		b, c = c, b
		c, d = d, c
		a, b = b, a

		c ^= g5(d + k[base+6])
		b ^= g21(a + k[base+5])
		d -= g13(c + k[base+4])

		e := g21(b+c+k[base+3]) ^ uint32(i)
		b -= e
		c += e

		a += g13(b + k[base+2])
		b ^= g5(a + k[base+0])
		c ^= g21(d + k[base+1])
	}

	binary.LittleEndian.PutUint32(dst[0:4], a)
	binary.LittleEndian.PutUint32(dst[4:8], b)
	binary.LittleEndian.PutUint32(dst[8:12], c)
	binary.LittleEndian.PutUint32(dst[12:16], d)
}

func g(x uint32, r int) uint32 {
	var y uint32
	for i := 0; i < 4; i++ {
		b := byte(x >> (8 * i))
		y |= uint32(sbox[b]) << (8 * i)
	}
	return bits.RotateLeft32(y, r)
}

func g5(x uint32) uint32  { return g(x, 5) }
func g13(x uint32) uint32 { return g(x, 13) }
func g21(x uint32) uint32 { return g(x, 21) }

func (m *Belt) roundKeys() [56]uint32 {
	var k [56]uint32
	for j := range k {
		k[j] = m.subkeys[j%8]
	}
	return k
}